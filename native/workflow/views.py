from django.shortcuts import render, redirect, get_object_or_404
from django.contrib.auth.decorators import login_required
from django.contrib import messages
from projects.models import Project
from .models import Artifact
from .forms import ArtifactEditForm, ReviewForm
from .hitl_service import hitl_service, HITLServiceError

@login_required
def stage_detail_view(request, project_id, stage):
    project = get_object_or_404(Project, pk=project_id, owner=request.user)
    
    valid_stages = dict(Project.STAGE_CHOICES)
    if stage not in valid_stages:
        return redirect('project_detail', pk=project.pk)
        
    # Generate new AI artifact from scratch (Initial Generation)
    if request.method == 'POST' and request.POST.get('generate_ai'):
        try:
            hitl_service.generate_initial_artifact(project, stage, request.user)
            messages.success(request, f'Artifact generated by AI and validated by Jev.')
        except HITLServiceError as e:
            messages.error(request, str(e))
        except Exception as e:
            messages.error(request, f"System Error: {str(e)}")
            
        return redirect('stage_detail', project_id=project.pk, stage=stage)
        
    artifacts = Artifact.objects.filter(project=project, stage=stage).order_by('-version')
    latest_artifact = artifacts.first() if artifacts.exists() else None
    
    review_form = ReviewForm()
    
    code_files = []
    if stage == 'CODE' and latest_artifact:
        from .utils import parse_code_files
        code_files = parse_code_files(latest_artifact.content)
    
    context = {
        'project': project,
        'stage': stage,
        'stage_name': valid_stages[stage],
        'artifacts': artifacts,
        'latest_artifact': latest_artifact,
        'review_form': review_form,
        'code_files': code_files,
    }
    return render(request, 'workflow/stage_detail.html', context)

@login_required
def artifact_edit_view(request, artifact_id):
    artifact = get_object_or_404(Artifact, pk=artifact_id, project__owner=request.user)
    
    if request.method == 'POST':
        form = ArtifactEditForm(request.POST)
        if form.is_valid():
            try:
                hitl_service.edit_artifact(artifact, request.user, form.cleaned_data['content'])
                messages.success(request, 'New version created from your edits.')
                return redirect('stage_detail', project_id=artifact.project.pk, stage=artifact.stage)
            except Exception as e:
                messages.error(request, f"System Error: {str(e)}")
    else:
        form = ArtifactEditForm(initial={'content': artifact.content})
        
    context = {
        'artifact': artifact,
        'form': form,
    }
    return render(request, 'workflow/artifact_edit.html', context)

@login_required
def artifact_review_view(request, artifact_id):
    artifact = get_object_or_404(Artifact, pk=artifact_id, project__owner=request.user)
    
    if request.method == 'POST':
        action = request.POST.get('action')
        feedback = request.POST.get('feedback', '')
        
        try:
            if action == 'APPROVE':
                hitl_service.approve_artifact(artifact, request.user, feedback)
                messages.success(request, 'Artifact approved! Project stage advanced.')
                
            elif action == 'REJECT':
                hitl_service.reject_artifact(artifact, request.user, feedback)
                messages.warning(request, 'Artifact rejected. Waiting for regeneration or manual edit.')
                
            elif action == 'REGENERATE':
                messages.info(request, 'AI is regenerating the artifact based on your feedback...')
                hitl_service.regenerate_artifact(artifact, request.user, feedback)
                messages.success(request, 'Artifact regenerated successfully.')
                
        except HITLServiceError as e:
            messages.error(request, str(e))
        except Exception as e:
            messages.error(request, f"System Error: {str(e)}")
            
    return redirect('stage_detail', project_id=artifact.project.pk, stage=artifact.stage)
